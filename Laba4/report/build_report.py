import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from report_gost import Report  # noqa: E402

r = Report()
r.title_page(topic="Многомерные массивы", variant=8,
             group="ВИШ-14-24", student="Елимов М.Д.")

# 1. Постановка задачи
r.heading("1. Постановка задачи")
r.text("Вариант 8. Дана квадратная матрица. Найти строку с наибольшим и "
       "наименьшим произведением элементов. Вывести на печать найденные "
       "строки и произведения их элементов.")
r.text("Порядок матрицы n и ее элементы (целые числа) вводятся с клавиатуры. "
       "Произведение элементов строки вычисляется отдельным методом product(), "
       "в который передается строка matrix[i]. Если наибольшее или наименьшее "
       "произведение имеют несколько строк, выводится первая из них.")

# 2. Входные, выходные, расчетные данные
r.heading("2. Входные, выходные, расчетные данные")
r.text("Входные, выходные и расчетные данные программы приведены в таблице 1.",
       keep_next=True)
r.table(
    "Входные, выходные и расчетные данные",
    ["Вид данных", "Имя", "Тип", "Описание"],
    [
        ["Входные", "n", "int", "порядок квадратной матрицы"],
        ["Входные", "matrix", "int[][]", "элементы матрицы n × n"],
        ["Выходные", "matrix[maxRow], maxProduct", "int[], long",
         "строка с наибольшим произведением и это произведение"],
        ["Выходные", "matrix[minRow], minProduct", "int[], long",
         "строка с наименьшим произведением и это произведение"],
        ["Расчетные", "p", "long", "произведение элементов текущей строки"],
        ["Расчетные", "maxRow, minRow", "int", "индексы найденных строк"],
    ],
    widths_cm=[3.0, 5.0, 2.7, 5.8],
)

# 3. Блок-схема алгоритма
r.heading("3. Блок-схема алгоритма")
f_main, f_prod = r.next_figure(), r.next_figure() + 1
r.text(f"Блок-схема основного алгоритма показана на рисунке {f_main}, "
       f"блок-схема метода product() – на рисунке {f_prod}.", keep_next=True)
r.figure("Блок-схема основного алгоритма", HERE / "img" / "blok_skhema.png",
         height_cm=22)
r.text(f"В начале алгоритма (рисунок {f_main}) вводится порядок матрицы n, "
       "затем двумя вложенными циклами по i и j вводятся элементы matrix[i][j] "
       "построчно.")
r.text("Далее вычисляется произведение элементов первой строки, и оно "
       "принимается одновременно за наибольшее и наименьшее: maxProduct = "
       "minProduct = product(matrix[0]), maxRow = minRow = 0.")
r.text("В цикле по i от 1 до n − 1 для каждой строки вычисляется "
       "произведение p. Если p больше maxProduct, запоминаются новое "
       "наибольшее произведение и номер строки maxRow. Если p меньше "
       "minProduct, аналогично обновляются minProduct и minRow. Сравнение "
       "строгое, поэтому при равных произведениях остается первая строка.")
r.text("После цикла выводятся найденные строки и их произведения.")
r.text(f"Блок-схема метода product() показана на рисунке {f_prod}.",
       keep_next=True)
r.figure("Блок-схема метода product()", HERE / "img" / "blok_skhema_product.png",
         height_cm=10)
r.text("Метод присваивает переменной p значение 1 и в цикле умножает ее на "
       "каждый элемент строки, после чего возвращает p.")

# 4. Код программы
r.heading("4. Код программы")
r.text("Код программы (файл Laba4.java) приведен ниже.", keep_next=True)
r.code((ROOT / "Laba4" / "Laba4.java").read_text(encoding="utf-8"))
r.text("Пояснения к коду:")
r.text("– матрица хранится в двумерном массиве int[][] matrix, строка "
       "matrix[i] является одномерным массивом и передается в метод "
       "product() целиком;")
r.text("– произведение имеет тип long, так как произведение нескольких "
       "чисел типа int быстро выходит за пределы диапазона int;")
r.text("– метод rowToString() собирает элементы строки в одну строку "
       "текста через пробел для вывода;")
r.text("– номера строк при выводе увеличены на 1, так как индексы массива "
       "в Java начинаются с 0.")

# 5. Скриншоты с результатами
tests = [
    ("n = 3; строки 1 2 3 / 4 5 6 / -1 2 2",
     "наибольшее произведение – строка 2 (4 5 6), 120; "
     "наименьшее – строка 3 (-1 2 2), -4"),
    ("n = 4; строки 2 0 7 1 / 3 3 3 3 / -2 5 1 1 / 1 1 1 -1",
     "наибольшее – строка 2 (3 3 3 3), 81; наименьшее – строка 3 "
     "(-2 5 1 1), -10"),
    ("n = 2; строки 2 -3 / -4 -1",
     "наибольшее – строка 2 (-4 -1), 4; наименьшее – строка 1 (2 -3), -6"),
]
r.heading("5. Скриншоты с результатами")
first = r.next_figure()
r.text(f"Программа проверена на {len(tests)} наборах входных данных. "
       f"Результаты выполнения показаны на рисунках {first}–"
       f"{first + len(tests) - 1}.")
for i, (inp, expected) in enumerate(tests, start=1):
    r.text(f"Тест {i}. Входные данные: {inp}. Ожидаемый результат: {expected}.")
    r.text(f"Результат выполнения программы показан на рисунке "
           f"{r.next_figure()}.", keep_next=True)
    r.figure(f"Результат выполнения программы, тест {i}")  # место под скриншот

r.save(HERE / "Otchet_Laba4_Elimov.docx")

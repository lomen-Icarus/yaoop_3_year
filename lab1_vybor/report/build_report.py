"""Отчёт по лабораторной работе №1 «Структуры выбора», вариант 8.

Запуск из корня репозитория:  python lab1_vybor/report/build_report.py
Результат: lab1_vybor/report/Otchet_Laba1_Elimov.docx
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from report_gost import Report  # noqa: E402

r = Report()
r.title_page(topic="Структуры выбора", variant=8)

# 1. Постановка задачи
r.heading("1. Постановка задачи")
r.text("Вариант 8. Даны действительные числа a, b, c. Удвоить эти числа, "
       "если a < b < c, и заменить их абсолютными значениями, если это не так.")
r.text("Условие a < b < c понимается как строгое возрастание чисел и в "
       "программе записывается как a < b && b < c. Если оно выполняется, "
       "каждое число умножается на 2, иначе каждое число заменяется своим "
       "модулем (метод Math.abs). Программа выводит полученные значения a, b, c.")

# 2. Входные, выходные, расчетные данные
r.heading("2. Входные, выходные, расчетные данные")
r.text("Входные, выходные и расчетные данные программы приведены в таблице 1.",
       keep_next=True)
r.table(
    "Входные, выходные и расчетные данные",
    ["Вид данных", "Имя", "Тип", "Описание"],
    [
        ["Входные", "a, b, c", "double", "исходные действительные числа"],
        ["Выходные", "a, b, c", "double",
         "удвоенные числа или их абсолютные значения"],
        ["Расчетные", "a < b && b < c", "boolean",
         "условие строгого возрастания чисел"],
    ],
    widths_cm=[3.3, 4.2, 2.6, 6.4],
)

# 3. Блок-схема алгоритма
r.heading("3. Блок-схема алгоритма")
r.text(f"Блок-схема алгоритма показана на рисунке {r.next_figure()}.",
       keep_next=True)
r.figure("Блок-схема алгоритма", HERE / "img" / "blok_skhema.png",
         height_cm=16)

# 4. Код программы
r.heading("4. Код программы")
r.text("Код программы (файл Main.java) приведен ниже.", keep_next=True)
r.code((ROOT / "lab1_vybor" / "src" / "Main.java").read_text(encoding="utf-8"))

# 5. Скриншоты с результатами
tests = [
    ("a = 1, b = 2.5, c = 4",
     "условие выполняется, a = 2.0, b = 5.0, c = 8.0"),
    ("a = -5, b = 3, c = -1",
     "условие не выполняется, a = 5.0, b = 3.0, c = 1.0"),
    ("a = -3, b = -2, c = -1",
     "условие выполняется, a = -6.0, b = -4.0, c = -2.0"),
    ("a = 4, b = 4, c = 7",
     "условие не выполняется (a = b, неравенство строгое), "
     "a = 4.0, b = 4.0, c = 7.0"),
]
r.heading("5. Скриншоты с результатами")
first = r.next_figure()
r.text(f"Программа проверена на {len(tests)} наборах входных данных. "
       f"Результаты выполнения показаны на рисунках {first}–"
       f"{first + len(tests) - 1}.")
for i, (inp, expected) in enumerate(tests, start=1):
    r.text(f"Тест {i}. Входные данные: {inp}. Ожидаемый результат: {expected}.")
    r.text(f"Результат выполнения программы показан на рисунке "
           f"{r.next_figure()}.", keep_next=True)
    r.figure(f"Результат выполнения программы, тест {i}")  # место под скриншот

r.save(HERE / "Otchet_Laba1_Elimov.docx")
print("OK:", HERE / "Otchet_Laba1_Elimov.docx")

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from report_gost import Report  # noqa: E402

N = " "  # неразрывный пробел

r = Report()
r.title_page(topic="Одномерные массивы", variant=8,
             group="ВИШ-14-24", student="Елимов М.Д.")

# 1. Постановка задачи
r.heading("1. Постановка задачи")
r.text("Вариант 8. Дана последовательность целых чисел a1, a2, ..., an. "
       "Указать пары чисел ai, aj, таких, что ai + aj = m.")
r.text(f"Количество чисел n (n{N}≥{N}2), сами числа и значение m вводятся с "
       "клавиатуры. Пару образуют два элемента с разными номерами i < j. Для "
       "каждой найденной пары выводятся номера элементов (нумерация с 1) и их "
       "значения. Если ни одной пары нет, выводится соответствующее сообщение.")

# 2. Входные, выходные, расчетные данные
r.heading("2. Входные, выходные, расчетные данные")
r.text("Входные, выходные и расчетные данные программы приведены в таблице 1.",
       keep_next=True)
r.table(
    "Входные, выходные и расчетные данные",
    ["Вид данных", "Имя", "Тип", "Описание"],
    [
        ["Входные", "n", "int", f"количество чисел (n{N}≥{N}2)"],
        ["Входные", "a", "int[]", "последовательность чисел"],
        ["Входные", "m", "int", "требуемая сумма пары"],
        ["Выходные", "i + 1, j + 1, a[i], a[j]", "int",
         "номера и значения элементов пары"],
        ["Выходные", "count", "int", "количество найденных пар"],
        ["Расчетные", "i, j", "int", "индексы элементов пары"],
    ],
    widths_cm=[3.1, 4.6, 2.2, 6.6],
)

# 3. Блок-схема алгоритма
r.heading("3. Блок-схема алгоритма")
r.text(f"Блок-схема алгоритма показана на рисунке {r.next_figure()}.",
       keep_next=True)
fig = r.figure("Блок-схема алгоритма", HERE / "img" / "blok_skhema.png",
               height_cm=22)
r.text(f"Алгоритм, показанный на рисунке {fig}, выполняется в три этапа.")
r.text(f"Сначала вводится количество чисел n. Ввод повторяется, пока не будет "
       f"выполнено условие n{N}≥{N}2, так как для пары нужны хотя бы два "
       "числа. Затем в цикле с параметром i от 0 до n − 1 вводятся элементы "
       "массива a, после чего вводится требуемая сумма m, а счетчику пар count "
       "присваивается значение 0.")
r.text("Далее выполняется перебор всех пар элементов с помощью двух вложенных "
       "циклов. Внешний цикл перебирает индекс i от 0 до n − 2, внутренний – "
       "индекс j от i + 1 до n − 1. Так как j всегда больше i, каждая пара "
       "рассматривается один раз и элемент не складывается сам с собой. Если "
       "a[i] + a[j] = m, счетчик count увеличивается на 1 и пара выводится "
       "на экран.")
r.text("После завершения циклов проверяется значение count. Если оно равно "
       "0, выводится сообщение о том, что пар нет, иначе выводится количество "
       "найденных пар.")

# 4. Код программы
r.heading("4. Код программы")
r.text("Код программы (файл Laba3.java) приведен ниже.", keep_next=True)
r.code((ROOT / "Laba3" / "Laba3.java").read_text(encoding="utf-8"))
r.text("Пояснения к коду:")
r.text("– массив создается оператором new int[n] после ввода n, поэтому его "
       "длина равна введенному количеству чисел;")
r.text("– элементы массива нумеруются в Java с 0, а в условии задачи – с 1, "
       "поэтому при выводе к индексам добавляется 1 (i + 1, j + 1);")
r.text("– условие внутреннего цикла j = i + 1 исключает повторный вывод "
       "одной и той же пары (например, a1 + a4 и a4 + a1);")
r.text("– сложность перебора – n · (n − 1) / 2 проверок, что для учебных "
       "размеров массива выполняется мгновенно.")

# 5. Скриншоты с результатами
tests = [
    ("n = 7; числа 1 5 3 7 2 6 4; m = 8",
     "a1 + a4 = 1 + 7, a2 + a3 = 5 + 3, a5 + a6 = 2 + 6; всего 3 пары"),
    ("n = 5; числа -2 10 5 3 0; m = 3",
     "a1 + a3 = -2 + 5, a4 + a5 = 3 + 0; всего 2 пары"),
    ("n = 3; числа 2 4 6; m = 5", "«Пар с суммой 5 нет»"),
    ("n = 3; числа 4 4 4; m = 8",
     "a1 + a2, a1 + a3, a2 + a3 (все пары равны 4 + 4); всего 3 пары"),
]
r.heading("5. Скриншоты с результатами")
first = r.next_figure()
r.text(f"Программа проверена на {len(tests)} наборах входных данных. "
       f"Результаты выполнения показаны на рисунках {first}–"
       f"{first + len(tests) - 1}.")
for i, (inp, expected) in enumerate(tests, start=1):
    r.text(f"Тест {i}. Входные данные: {inp}. Ожидаемый результат: {expected}.")
    r.text(f"Результат выполнения программы показан на рисунке "
           f"{r.next_figure()}.", keep_next=True)
    r.figure(f"Результат выполнения программы, тест {i}")  # место под скриншот

r.save(HERE / "Otchet_Laba3_Elimov.docx")
